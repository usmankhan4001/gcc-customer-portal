import React from 'react';
import { randomBytes } from 'crypto';
import { Document, Page, Text, View, StyleSheet, renderToBuffer } from '@react-pdf/renderer';
import { uploadBuffer } from '@/lib/r2';

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 11, fontFamily: 'Helvetica', color: '#0F172A', backgroundColor: '#FFFFFF' },
  header: { backgroundColor: '#14204A', padding: 24, marginBottom: 24, borderRadius: 8 },
  brand: { color: '#F26522', fontSize: 12, fontWeight: 700, textTransform: 'uppercase', letterSpacing: 1.5, marginBottom: 6 },
  title: { color: '#FFFFFF', fontSize: 20, fontWeight: 700 },
  subtitle: { color: '#FFFFFF', fontSize: 11, marginTop: 4, opacity: 0.85 },
  row: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    paddingVertical: 10,
    borderBottomWidth: 1,
    borderBottomColor: '#E2E8F0',
  },
  label: { color: '#64748B', fontSize: 11 },
  value: { color: '#0F172A', fontSize: 11, fontWeight: 700 },
  disclaimer: { marginTop: 32, fontSize: 9, color: '#94A3B8', lineHeight: 1.5 },
  footer: { position: 'absolute', bottom: 30, left: 40, right: 40, fontSize: 9, color: '#94A3B8', textAlign: 'center' },
});

export interface PDFRow {
  label: string;
  value: string;
}

export interface GenerateToolPDFParams {
  title: string;
  subtitle?: string;
  rows: PDFRow[];
  disclaimer?: string;
  r2KeyPrefix?: string; // e.g. 'pdfs/tax-calculator'
}

export function ToolResultDocument({ title, subtitle, rows, disclaimer }: GenerateToolPDFParams) {
  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.brand}>GCC Startup &bull; Official Advisory</Text>
          <Text style={styles.title}>{title}</Text>
          {subtitle && <Text style={styles.subtitle}>{subtitle}</Text>}
        </View>

        {rows.map((row, idx) => (
          <View key={idx} style={styles.row}>
            <Text style={styles.label}>{row.label}</Text>
            <Text style={styles.value}>{row.value}</Text>
          </View>
        ))}

        {disclaimer && <Text style={styles.disclaimer}>{disclaimer}</Text>}

        <Text style={styles.footer}>
          Generated by GCC Startup &bull; {new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}
        </Text>
      </Page>
    </Document>
  );
}

export async function generateToolPDFBuffer(params: GenerateToolPDFParams): Promise<Buffer> {
  return await renderToBuffer(<ToolResultDocument {...params} />);
}

export async function generateToolPDF(params: GenerateToolPDFParams): Promise<{ r2Key: string; buffer?: Buffer }> {
  const buffer = await renderToBuffer(<ToolResultDocument {...params} />);
  const prefix = params.r2KeyPrefix || 'pdfs/general';
  const r2Key = `${prefix}/${Date.now()}-${randomBytes(4).toString('hex')}.pdf`;
  try {
    await uploadBuffer(r2Key, buffer, 'application/pdf');
  } catch (err) {
    console.warn('[PDF] R2 upload failed or not configured, returning buffer:', err);
  }
  return { r2Key, buffer };
}
