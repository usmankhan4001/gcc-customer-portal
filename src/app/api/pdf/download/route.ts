import { NextResponse } from 'next/server';
import { generateToolPDFBuffer, type PDFRow } from '@/lib/pdf';

export const dynamic = 'force-dynamic';

interface DownloadPDFRequest {
  title: string;
  subtitle?: string;
  rows: PDFRow[];
  disclaimer?: string;
  filename?: string;
}

export async function POST(request: Request) {
  try {
    const body = (await request.json()) as DownloadPDFRequest;
    const { title, subtitle, rows, disclaimer, filename } = body;

    if (!title || !rows?.length) {
      return NextResponse.json({ error: 'Title and rows are required' }, { status: 400 });
    }

    const buffer = await generateToolPDFBuffer({
      title,
      subtitle,
      rows,
      disclaimer:
        disclaimer ||
        'This document is generated by GCC Startup platform advisory tools. It does not constitute formal tax, legal, or filing opinion until verified by licensed counsel.',
    });

    const safeFilename = (filename || `${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.pdf`)
      .replace(/[^a-zA-Z0-9_.-]/g, '_');

    const uint8 = new Uint8Array(buffer);

    return new NextResponse(uint8, {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="${safeFilename}"`,
        'Content-Length': buffer.length.toString(),
      },
    });
  } catch (error: any) {
    console.error('[api/pdf/download] Error:', error);
    return NextResponse.json({ error: 'Failed to generate PDF' }, { status: 500 });
  }
}
