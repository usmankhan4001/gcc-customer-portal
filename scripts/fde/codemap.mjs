#!/usr/bin/env node
// Regenerates docs/ai/CODEMAP.md from the source tree so AI docs never drift. Run: npm run docs:ai
import fs from 'node:fs';
import path from 'node:path';

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    e.isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
};
const rel = (p) => p.split(path.sep).join('/');
const routeOf = (file) => '/' + rel(path.relative('src/app', path.dirname(file))).split('/').filter((s) => s && !/^\(.*\)$/.test(s) && s !== '.').join('/');

const app = walk('src/app').map(rel);
const pages = app.filter((f) => f.endsWith('/page.tsx')).map((f) => routeOf(f)).sort();
const apis = app
  .filter((f) => f.endsWith('/route.ts'))
  .map((f) => {
    const methods = [...fs.readFileSync(f, 'utf8').matchAll(/export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE)/g)].map((m) => m[1]);
    return `${routeOf(f)}  [${methods.join(', ') || '?'}]`;
  })
  .sort();
const tables = [...fs.readFileSync('src/lib/db/schema.ts', 'utf8').matchAll(/export const (\w+)\s*=\s*pgTable\(\s*['"](\w+)['"]/g)].map((m) => `${m[2]} (${m[1]})`);
const libs = walk('src/lib')
  .map(rel)
  .filter((f) => /\.tsx?$/.test(f) && !f.endsWith('.test.ts'))
  .map((f) => {
    const names = [...fs.readFileSync(f, 'utf8').matchAll(/export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)/g)].map((m) => m[1]);
    return `${f}: ${names.join(', ') || '-'}`;
  });
const list = (a) => a.map((x) => `- ${x}`).join('\n');

fs.writeFileSync(
  'docs/ai/CODEMAP.md',
  `# Code Map (generated)\n\n> Generated by \`npm run docs:ai\` from the source tree. Do not edit by hand.\n\n## Pages (${pages.length})\n${list(pages)}\n\n## API routes (${apis.length})\n${list(apis)}\n\n## DB tables (${tables.length})\n${list(tables)}\n\n## src/lib modules\n${list(libs)}\n`
);
console.log(`docs/ai/CODEMAP.md: ${pages.length} pages, ${apis.length} api routes, ${tables.length} tables`);

// docs/ai/FEATURES.md: generated index of docs/ai/features/*.md so agents never hand-edit a shared table.
const featDir = 'docs/ai/features';
const featRows = fs
  .readdirSync(featDir)
  .filter((f) => f.endsWith('.md') && !f.startsWith('_'))
  .sort()
  .map((f) => {
    const md = fs.readFileSync(path.join(featDir, f), 'utf8');
    const slug = f.replace(/\.md$/, '');
    const title = /^#\s+(?:Feature:\s*)?(.+)$/m.exec(md)?.[1]?.trim() || slug;
    const status = /\*\*Status\*\*:\s*([a-z-]+)/i.exec(md)?.[1] || '-';
    const spec = /\*\*Spec\*\*:\s*(\S+\.md)/.exec(md)?.[1];
    const area = /modules\/([a-z-]+)\.md/.exec(md)?.[1] || '-';
    return `| [${slug}](features/${f}) | ${title} | ${area} | ${status} | ${spec ? `[spec](${spec.replace(/^docs\//, '../')})` : ''} |`;
  });
fs.writeFileSync(
  'docs/ai/FEATURES.md',
  `# Feature Index (generated)\n\n> Generated by \`npm run docs:ai\` from docs/ai/features/*.md. Do not edit or commit. Hand-written overview: [MODULES.md](MODULES.md).\n\n| Slug | Title | Area | Status | Spec |\n| :--- | :--- | :--- | :--- | :--- |\n${featRows.join('\n')}\n`
);
console.log(`docs/ai/FEATURES.md: ${featRows.length} features`);
